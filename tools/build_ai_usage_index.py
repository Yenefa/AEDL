"""AI usage ledger: split storage, generated index, fail-closed validation.

History (GH-49, ADR-012): the ledger was a single append-only file
(docs/compliance/AI_USAGE_LOG.md) with per-day globally increasing IDs.
Under parallel branches that design produced both Git text conflicts
(every branch appends at the same tail of one file) and semantic ID
collisions (each agent picks max+1 from its own stale view). The storage
is now one file per entry plus a GENERATED index; IDs carry an actor
prefix so concurrent issuers can never collide.

Storage layout:

    docs/compliance/AI_USAGE_LOG.md      GENERATED index — never hand-edit
    docs/compliance/ai-usage/<ID>.md     one auditable work unit per file

ID formats (both accepted; legacy records are NOT renumbered):
    AI-YYYYMMDD-NNN            legacy, pre GH-49
    AI-YYYYMMDD-<ACTOR>-<NN>   current; ACTOR must be a registered actor

Commands (single entry point, same on every platform):

    python -m tools.build_ai_usage_index migrate   # split ledger tail into per-entry files
    python -m tools.build_ai_usage_index build     # regenerate AI_USAGE_LOG.md from ai-usage/
    python -m tools.build_ai_usage_index check     # fail-closed validation (dev_gate calls this)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

LEDGER_PATH = Path("docs/compliance/AI_USAGE_LOG.md")
ENTRIES_DIR = Path("docs/compliance/ai-usage")
INDEX_MARKER = "<!-- GENERATED by tools/build_ai_usage_index.py build — DO NOT EDIT. Source of truth: docs/compliance/ai-usage/ -->"

# Legacy daily-global sequence (GH-49 前存量，不追溯改号) and current actor format.
LEGACY_ID_RE = re.compile(r"^AI-(\d{8})-(\d{3})$")
ACTOR_ID_RE = re.compile(r"^AI-(\d{8})-([A-Z]{2,10})-(\d{2,4})$")
# Actor codes registered in docs/ID_MAP.md + docs/COLLABORATION.md (human or agent).
REGISTERED_ACTORS = {"YEN", "PER", "LIO", "CODEX", "ZCODE", "CLAUDE", "OPENCODE", "BOT"}


class LedgerError(Exception):
    """Validation failure — rendered as check findings, never a traceback."""


def _repo_root(root: Path) -> Path:
    if (root / ".git").exists():
        return root
    raise LedgerError(f"not a git repository: {root}")


def entry_path(root: Path, entry_id: str) -> Path:
    return root / ENTRIES_DIR / f"{entry_id}.md"


def parse_date(entry_id: str) -> str:
    m = LEGACY_ID_RE.match(entry_id) or ACTOR_ID_RE.match(entry_id)
    return m.group(1) if m else ""


def list_entry_files(root: Path) -> list:
    d = root / ENTRIES_DIR
    if not d.is_dir():
        return []
    return sorted(
        p for p in d.iterdir()
        if p.is_file() and p.suffix == ".md" and p.name != "README.md"
    )


def entry_id_from_text(text: str, source: str) -> str:
    m = re.search(r"^## (AI-\S+)\s*$", text, re.M)
    if not m:
        raise LedgerError(f"{source}: no '## AI-...' heading")
    return m.group(1)


def read_entries(root: Path) -> list:
    """[(entry_id, text)] for every per-entry file, sorted by ID."""
    entries = []
    for p in list_entry_files(root):
        text = p.read_text(encoding="utf-8")
        entry_id = entry_id_from_text(text, str(p.relative_to(root)))
        if p.stem != entry_id:
            raise LedgerError(f"{p.relative_to(root)}: filename does not match heading {entry_id}")
        entries.append((entry_id, text))
    entries.sort(key=lambda e: e[0])
    return entries


# ---------------------------------------------------------------- migrate

def split_ledger_text(text: str, source: str) -> list:
    """Split a ledger markdown text into [(entry_id, body)] preserving bytes.

    body is everything from the entry heading line (inclusive) up to the next
    entry heading; leading/trailing blank lines outside that block are dropped,
    everything inside is untouched (byte-faithful migration).
    """
    headings = list(re.finditer(r"^## (AI-\S+)\s*$", text, re.M))
    if not headings:
        raise LedgerError(f"{source}: no '## AI-...' entries to migrate")
    seen = set()
    out = []
    for i, m in enumerate(headings):
        entry_id = m.group(1)
        if entry_id in seen:
            raise LedgerError(f"{source}: duplicate entry heading {entry_id}")
        seen.add(entry_id)
        start = m.start()
        end = headings[i + 1].start() if i + 1 < len(headings) else len(text)
        body = text[start:end].rstrip("\n") + "\n"
        out.append((entry_id, body))
    return out


def cmd_migrate(root: Path) -> dict:
    """Append-only migration: entries already present as files are skipped, so
    a ledger that grew since the last run can be re-migrated safely (and the
    same entry content in both places is expected until the index is rebuilt)."""
    ledger = root / LEDGER_PATH
    text = ledger.read_text(encoding="utf-8") if ledger.is_file() else ""
    if not text.strip():
        return {"migrated": [], "skipped": 0, "total_files": len(list_entry_files(root))}
    out_dir = root / ENTRIES_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    migrated, skipped = [], 0
    for entry_id, body in split_ledger_text(text, str(LEDGER_PATH)):
        target = entry_path(root, entry_id)
        if target.is_file():
            skipped += 1
            continue
        target.write_text(body, encoding="utf-8", newline="\n")
        migrated.append(entry_id)
    return {
        "migrated": migrated,
        "skipped": skipped,
        "total_files": len(list_entry_files(root)),
    }


# ------------------------------------------------------------------ build

def build_index_text(entries: list) -> str:
    lines = [
        "# AI Usage Log",
        "",
        INDEX_MARKER,
        "",
        "> 项目内所有实质 AI 贡献按条目文件记录于 `docs/compliance/ai-usage/`，",
        "> 本文件是自动生成的索引。**禁止手工编辑本文件**——改动会被下次生成覆盖，",
        "> 且 dev_gate 的 `ai_usage_ledger` 检查会 fail-closed。",
        "> 新增条目：在 `ai-usage/` 下新建 `<ID>.md` 后运行",
        "> `python -m tools.build_ai_usage_index build`（或让 dev_gate/CI 校验）。",
        "> ID 规则与审核状态约定见 `AGENTS.md` §4 与 ADR-012。",
        "",
        f"共 {len(entries)} 条。完整正文在各自条目文件中；本索引只做导航。",
        "",
    ]
    current_day = None
    for entry_id, text in entries:
        day = parse_date(entry_id)
        if day != current_day:
            current_day = day
            lines.append(f"## {day[:4]}-{day[4:6]}-{day[6:]}")
            lines.append("")
        first = ""
        for raw in text.splitlines()[1:]:
            s = raw.strip()
            if not s or s.startswith(">") or s.startswith("## "):
                continue
            m = re.match(r"^-\s*任务名称\s*[：:]\s*(.+)$", s)
            if m:
                first = m.group(1).strip()
                break
            if first:
                continue
            m2 = re.match(r"^-\s*([^：:]+)[：:]", s)
            if not m2 or m2.group(1).strip() in {"日期", "会话", "人工审核"}:
                continue
            first = s.lstrip("- ").strip()
        lines.append(f"- [`{entry_id}`](ai-usage/{entry_id}.md) — {first}")
        if not first:
            first = "(no summary line)"
    lines.append("")
    return "\n".join(lines)


def cmd_build(root: Path) -> dict:
    entries = read_entries(root)
    if not entries:
        raise LedgerError("no per-entry files under docs/compliance/ai-usage/ — refuse to blank the index")
    (root / LEDGER_PATH).write_text(build_index_text(entries), encoding="utf-8", newline="\n")
    return {"index_entries": len(entries)}


# ------------------------------------------------------------------ check

def check_ledger(root: Path) -> list:
    """Fail-closed findings list; empty means healthy. Any LedgerError raised
    while reading entries becomes a finding itself, not a crash."""
    findings = []
    try:
        entries = read_entries(root)
    except LedgerError as exc:
        return [str(exc)]
    if not entries:
        return ["no per-entry files under docs/compliance/ai-usage/"]
    ids = [e[0] for e in entries]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        findings.append(f"duplicate entry IDs: {sorted(dupes)}")
    for entry_id, text in entries:
        rel = f"ai-usage/{entry_id}.md"
        m = LEGACY_ID_RE.match(entry_id) or ACTOR_ID_RE.match(entry_id)
        if not m:
            findings.append(f"{rel}: ID does not match any accepted format")
            continue
        if ACTOR_ID_RE.match(entry_id):
            actor = ACTOR_ID_RE.match(entry_id).group(2)
            if actor not in REGISTERED_ACTORS:
                findings.append(f"{rel}: actor {actor} not registered (see docs/ID_MAP.md)")
        day = parse_date(entry_id)
        date_field = re.search(r"^-\s*日期\s*[：:]\s*(\d{4})-(\d{2})-(\d{2})", text, re.M)
        if date_field:
            iso = f"{date_field.group(1)}{date_field.group(2)}{date_field.group(3)}"
            if iso != day:
                findings.append(f"{rel}: 日期字段 {date_field.group(1)}-... != ID 日期 {day}")
        else:
            findings.append(f"{rel}: missing 日期 field")
        if "PENDING_HUMAN_REVIEW" not in text and "HUMAN_REVIEWED" not in text and "ACCEPTED" not in text:
            findings.append(f"{rel}: no review-status marker")
    # index agreement: the generated index must reference exactly the entry set
    ledger = root / LEDGER_PATH
    if not ledger.is_file():
        findings.append(f"{LEDGER_PATH}: missing (run: build)")
    else:
        index_text = ledger.read_text(encoding="utf-8")
        if INDEX_MARKER not in index_text:
            findings.append(f"{LEDGER_PATH}: missing GENERATED marker (hand-edited? run: build)")
        linked = set(re.findall(r"\(ai-usage/(AI-\S+)\.md\)", index_text))
        if linked != set(ids):
            missing = sorted(set(ids) - linked)
            extra = sorted(linked - set(ids))
            findings.append(f"{LEDGER_PATH}: index out of sync (missing={missing}, extra={extra}) — run: build")
    # stray files that are neither the index nor an entry file
    allowed = {str(LEDGER_PATH)}
    for p in list_entry_files(root):
        allowed.add(str(ENTRIES_DIR / p.name))
    return findings


def cmd_check(root: Path, as_json: bool) -> int:
    try:
        findings = check_ledger(root)
    except LedgerError as exc:
        findings = [str(exc)]
    if as_json:
        print(json.dumps({"findings": findings, "ok": not findings}, ensure_ascii=False, indent=2))
    else:
        for f in findings:
            print(f"FINDING: {f}", file=sys.stderr)
        print("OK" if not findings else f"{len(findings)} finding(s)", file=sys.stderr)
    return 0 if not findings else 1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["migrate", "build", "check"])
    parser.add_argument("--root", default=None, help="repo root (default: auto from this file)")
    parser.add_argument("--json", action="store_true", help="check: emit JSON findings")
    args = parser.parse_args(argv)
    root = Path(args.root).resolve() if args.root else Path(__file__).resolve().parents[1]
    _repo_root(root)
    if args.command == "migrate":
        result = cmd_migrate(root)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    if args.command == "build":
        result = cmd_build(root)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    return cmd_check(root, as_json=args.json)


if __name__ == "__main__":
    sys.exit(main())
